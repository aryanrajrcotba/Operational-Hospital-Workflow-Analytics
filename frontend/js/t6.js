  async function gunzip(b64) {
    const bin = Uint8Array.from(atob(b64), (c) => c.charCodeAt(0));
    const stream = new Blob([bin]).stream().pipeThrough(new DecompressionStream("gzip"));
    return new Uint8Array(await new Response(stream).arrayBuffer());
  }
  function loadVolume() {
    if (volPromise) return volPromise;
    volPromise = new Promise((res, rej) => {
      if (window.VOLUME) return res(window.VOLUME);
      const s = document.createElement("script");
      s.src = "data/t6_volume.js"; s.onload = () => res(window.VOLUME); s.onerror = () => rej(new Error("data/t6_volume.js not found - run python -m pipeline.build"));
      document.head.appendChild(s);
    }).then(async (V) => {
      if (typeof DecompressionStream === "undefined") throw new Error("this browser has no DecompressionStream (needs Chrome 80+, Safari 16.4+, Firefox 113+)");
      const h = await gunzip(V.hu), l = await gunzip(V.labels);
      return { shape: V.shape, hu: new Int16Array(h.buffer, h.byteOffset, h.byteLength / 2), labels: l };
    });
    volPromise.catch(() => { volPromise = null; });
    return volPromise;
  }

