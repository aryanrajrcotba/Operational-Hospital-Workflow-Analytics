        if (mode === "slice") { const [x, y, z] = vox[k](u, v, tc); val = hu[at(x, y, z)]; }
        else {
          let acc = mode === "minip" ? 4000 : mode === "mip" ? -4000 : 0;
          for (let t = t0; t <= t1; t++) {
            const [x, y, z] = vox[k](u, v, t), q = at(x, y, z), s = hu[q];
            if (mode === "mip") { if (s > acc) acc = s; } else if (mode === "minip") { if (s < acc) acc = s; } else acc += s;
            if (lab[q] === 2) isNod = true;
          }
          val = mode === "avg" ? acc / nSl : acc;
        }
        const [xc, yc, zc] = vox[k](u, v, tc), lb = lab[at(xc, yc, zc)];
