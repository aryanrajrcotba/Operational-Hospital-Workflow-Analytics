  function lutOf(id) {
    if (lutCache[id]) return lutCache[id];
    const st = CM[id].stops, out = new Uint8ClampedArray(256 * 3), n = st.length - 1;
    for (let i = 0; i < 256; i++) {
      const t = (i / 255) * n, k = Math.min(n - 1, Math.floor(t)), f = t - k;
      for (let c = 0; c < 3; c++) out[i * 3 + c] = st[k][c] + (st[k + 1][c] - st[k][c]) * f;
    }
    return (lutCache[id] = out);
  }
